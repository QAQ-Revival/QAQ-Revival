const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async ({ evaluate, waitFor, captureUI, window, root, passed, handlers, attachmentRequests, attachmentBytes, externalLinks, protectedLink, protectedNormal, revivalChildren, setSelection }) => {
  const directory = path.join(root, 'attachment-cache'); fs.mkdirSync(directory, { recursive: true });
  setSelection({ canceled: false, filePaths: [directory] });
  assert.equal((await evaluate('window.api.marketSelectDownloadCacheDir()')).success, true);
  await window.loadFile(path.join(process.resourcesPath, 'app/out/renderer/index.html'));
  await waitFor(`!!document.querySelector('.nav-item[aria-label="MOD下载"]')`, 'download navigation');
  await evaluate(`document.querySelector('.nav-item[aria-label="MOD下载"]').click()`);
  for (const [source, host] of [['pawchive', 'file.pawchive.pw'], ['kemono', 'n3.kemono.cr']]) {
    await waitFor(`!!document.querySelector('.mod-download-source-trigger')`, 'source selector');
    await evaluate(`document.querySelector('.mod-download-source-trigger').click()`);
    await waitFor(`!!document.querySelector('.mod-download-source-option[data-source="${source}"]')`, 'source option');
    await evaluate(`document.querySelector('.mod-download-source-option[data-source="${source}"]').click()`);
    await waitFor(`!!document.getElementById('${source}-tab-posts')`, 'latest posts tab');
    await evaluate(`document.getElementById('${source}-tab-posts').click()`);
    await waitFor(`!!document.querySelector('.mod-download-provider[data-source="${source}"] .paw-card-image')`, 'post card');
    await evaluate(`document.querySelector('.mod-download-provider[data-source="${source}"] .paw-card-image').click()`);
    await waitFor(`document.querySelector('.paw-gallery-counter')?.textContent === '1 / 3' && !!document.querySelector('.paw-files .paw-file')`, 'complete post');
    const files = await evaluate(`Array.from(document.querySelectorAll('.paw-files .paw-file')).map(x=>x.textContent)`);
    assert.equal(files.length, 1); assert.match(files[0], /mod\.zip/); assert.doesNotMatch(files[0], /png/i);
    assert.ok(await evaluate(`Array.from(document.querySelectorAll('.paw-content-links button')).some(x=>x.title === ${JSON.stringify(protectedLink)})`));
    const openedBefore = externalLinks.length;
    await evaluate(`document.querySelector('.paw-files .paw-file').click()`);
    await waitFor(`Array.from(document.querySelectorAll('.qaqm-download-item')).some(x=>x.textContent.includes('mod.zip') && x.classList.contains('status-completed'))`, 'built-in attachment complete');
    await waitFor(`window.api.attachmentTasks().then(result=>result.tasks.some(task=>task.source === '${source}' && task.status === 'completed'))`, 'source attachment complete');
    const result = await handlers.get('attachment:list')({});
    const task = result.tasks.find(item => item.source === source);
    assert.equal(task.status, 'completed');
    assert.ok(fs.readFileSync(task.archivePath).equals(attachmentBytes));
    assert.deepEqual((await handlers.get('attachment:importPaths')({}, { taskId: task.taskId })).paths, [task.archivePath]);
    assert.equal(externalLinks.length, openedBefore, 'attachment must not launch the browser');
    assert.ok(attachmentRequests.includes(`https://${host}/data/smoke/mod.zip?f=mod.zip`));
    await evaluate(`document.body.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true }))`);
    const workersBefore = revivalChildren.length;
    await evaluate(`document.querySelector('.paw-download-button').click()`);
    await waitFor(`!!document.querySelector('.paw-mega-selection input[type="password"]')`, 'password prompt');
    await evaluate(`document.querySelector('.paw-download-button').click()`);
    await waitFor(`document.querySelector('.paw-mega-download [role="alert"]')?.textContent.includes('填写作者提供的密码')`, 'missing password feedback');
    assert.equal(revivalChildren.length, workersBefore);
    await evaluate(`(() => { const input=document.querySelector('.paw-mega-selection input[type="password"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'smoke-password'); input.dispatchEvent(new Event('input',{bubbles:true})); })()`);
    await evaluate(`document.querySelector('.paw-download-button').click()`);
    await waitFor(`document.querySelector('.paw-mega-download [role="status"]')?.textContent.includes('已添加')`, 'protected share queued');
    await waitFor(`window.api.megaRevivalTasks().then(result=>result.tasks.some(task=>task.status === 'downloading'))`, 'protected share reaches worker');
    assert.ok(revivalChildren.some(child=>child.requests.some(request=>request.url===protectedNormal)));
    assert.ok(!fs.readFileSync(path.join(root, 'AppData/QAQ-Revival/mega-downloads.json'), 'utf8').includes('smoke-password'));
    await evaluate(`document.querySelector('[aria-label="关闭内容详情"]').click()`);
    passed(`${source}: gallery-only images, correct attachment CDN/name, real built-in HTTP download bytes, plain protected MEGA links and password prompt`);
  }
};
