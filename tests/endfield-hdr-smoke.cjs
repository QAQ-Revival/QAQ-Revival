const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
module.exports = async ({ evaluate, waitFor, captureUI, window, root, handlers, passed, hdrPreferences }) => {
  const call = (channel, ...args) => handlers.get(channel)({ sender: window.webContents }, ...args);
  const write = (file, value) => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, value); };
  const xxmi = path.join(root, 'hdr-XXMI'), efmi = path.join(xxmi, 'EFMI');
  const gamePath = path.join(root, 'hdr-game/Endfield.exe'), loader = path.join(xxmi, 'Resources/Bin/XXMI Launcher.exe');
  write(gamePath, 'Synthetic game'); write(loader, 'Synthetic launcher'); write(path.join(efmi, 'd3d11.dll'), 'DX11 fixture'); write(path.join(efmi, 'd3dx.ini'), '[System]\n');
  fs.mkdirSync(path.join(efmi, 'Mods'), { recursive: true });
  const importer = { importer_folder: efmi, game_folder: path.dirname(gamePath), d3d11_mode_cmd_args: '-force-d3d11', xxmi_dll_inject_mode: 'DIRECT' };
  const configFile = path.join(xxmi, 'XXMI Launcher Config.json');
  write(configFile, JSON.stringify({ Importers: { EFMI: { Importer: importer } } }));
  const updated = await call('game:update', { gameId: 'endfield', updates: { modLoaderPath: loader, modFolderPath: path.join(efmi, 'Mods'), gamePath } });
  assert.equal(updated.success, true, JSON.stringify(updated));
  await call('game:switch', 'endfield');
  await evaluate(`window.dispatchEvent(new CustomEvent('qaqm-navigate', { detail: { tab: 'characters' } }))`);
  await evaluate(`document.querySelector('.game-settings-button').click()`);
  await waitFor(`!!document.querySelector('[data-section="endfield-hdr"]')`, 'Endfield HDR navigation');
  await evaluate(`document.querySelector('[data-section="endfield-hdr"]').click()`);
  const auto = `document.querySelector('[aria-label="Windows Auto HDR"]')`;
  const native = `document.querySelector('[aria-label="RenoDX 原生 HDR"]')`;
  await waitFor(`!!${auto} && !${auto}.disabled && !${native}.disabled`, 'HDR controls ready');
  assert.equal(await evaluate(`${auto}.checked`), true);
  assert.equal(hdrPreferences.has(gamePath), false, 'opening the page does not write the registry');
  await captureUI('endfield-hdr-auto.png');
  await evaluate(`${native}.click()`);
  await waitFor(`${native}.checked && !${native}.disabled && !${auto}.checked`, 'native HDR excludes Auto HDR');
  assert.match(hdrPreferences.get(gamePath), /AutoHDREnable=2096;/);
  const nativeState = await call('endfield:hdr-status');
  assert.equal(nativeState.needsApproval, true); assert.equal(nativeState.installed, true);
  assert.ok(fs.existsSync(path.join(nativeState.paths.root, 'renodx-endfield.addon64')));
  await captureUI('endfield-hdr-native.png');
  const keys = crypto.generateKeyPairSync('ec', { namedCurve: 'secp384r1' });
  write(path.join(xxmi, 'Resources/Security/public_key.der'), keys.publicKey.export({ type: 'spki', format: 'der' }).toString('base64'));
  const accepted = JSON.parse(fs.readFileSync(configFile));
  accepted.Importers.EFMI.Importer.extra_libraries_signature = crypto.sign('sha256', Buffer.from(accepted.Importers.EFMI.Importer.extra_libraries), keys.privateKey).toString('base64');
  write(configFile, JSON.stringify(accepted));
  await evaluate(`${auto}.click()`);
  await waitFor(`${auto}.checked && !${auto}.disabled && !${native}.checked`, 'Auto HDR removes managed native injection');
  assert.deepEqual(JSON.parse(fs.readFileSync(configFile)).Importers.EFMI.Importer, importer);
  assert.match(hdrPreferences.get(gamePath), /AutoHDREnable=2097;/);
  await evaluate(`${native}.click()`);
  await waitFor(`${native}.checked && !${native}.disabled && !${auto}.checked`, 'native HDR returns with saved authorization');
  assert.equal((await call('endfield:hdr-status')).needsApproval, false);
  await captureUI('endfield-hdr-native-approved.png');
  await evaluate(`${auto}.click()`);
  await waitFor(`${auto}.checked && !${auto}.disabled && !${native}.checked`, 'Auto HDR restores the original settings again');
  await evaluate(`${auto}.click()`);
  await waitFor(`!${auto}.checked && !${auto}.disabled && !${native}.checked`, 'both HDR modes off');
  assert.equal((await call('endfield:hdr-status')).mode, 'off');
  assert.deepEqual(fs.readdirSync(path.dirname(gamePath)), ['Endfield.exe']);
  await captureUI('endfield-hdr-off.png');
  passed('Endfield HDR switches exclusively, reuses verified Launcher approval across mode changes, restores EFMI settings, and keeps the game directory clean');
};
