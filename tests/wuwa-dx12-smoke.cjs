const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
module.exports = async ({ call, click, evaluate, waitFor, captureUI, root, launchRequests, passed, gameRoot, xxmi }) => {
  const win64 = path.join(gameRoot, 'Client/Binaries/Win64'), wwmi = path.join(xxmi, 'WWMI');
  fs.mkdirSync(win64, { recursive: true }); fs.writeFileSync(path.join(win64, 'Client-Win64-Shipping.exe'), 'Synthetic game, never executed');
  fs.mkdirSync(path.join(wwmi, 'Mods'), { recursive: true }); fs.mkdirSync(path.join(wwmi, 'Core/WWMI'), { recursive: true }); fs.writeFileSync(path.join(wwmi, 'd3dx.ini'), '[Include]\n');
  await call('game:update', { gameId: 'wuthering-waves', updates: { modFolderPath: path.join(wwmi, 'Mods') } });
  await evaluate(`[...document.querySelectorAll('#settings-wuwa-dx12 button')].find(b => b.textContent === '重新检测').click()`);
  await waitFor(`!document.querySelector('[aria-label="鸣潮 DX12 Mod"]').disabled`, 'DX12 checks loaded');
  assert.equal((await call('wuwa:dx12-status')).sources.reshade.source, 'missing');
  assert.equal(fs.existsSync(path.join(win64, 'dxgi.dll')), false, 'opening settings never installs');
  await click('[aria-label="鸣潮 DX12 Mod"]');
  await waitFor(`document.querySelector('[aria-label="鸣潮 DX12 Mod"]').checked && !document.querySelector('[aria-label="鸣潮 DX12 Mod"]').disabled`, 'DX12 built-in installation');
  let state = await call('wuwa:dx12-status');
  assert.equal(state.ready, true); assert.equal(state.sources.reshade.source, 'managed'); assert.equal(state.sources.addon.source, 'managed');
  assert.equal((await call('get-config')).config.games.find(game => game.id === 'wuthering-waves').wuwaDx12Enabled, true);
  const configFile = path.join(root, 'AppData/QAQ-Revival/config.json');
  assert.equal(JSON.parse(fs.readFileSync(configFile)).games.find(game => game.id === 'wuthering-waves').wuwaDx12Enabled, true, 'DX12 switch is saved on disk');
  await waitFor(`document.querySelector('[aria-label="启动游戏"]').textContent.includes('DX12')`, 'DX12 launch label');
  await evaluate(`[...document.querySelectorAll('#settings-wuwa-dx12 button')].find(b => b.textContent === '检查更新').click()`);
  await waitFor(`!document.querySelector('[aria-label="wwmi-dx12 更新内置组件"]').disabled`, 'new component release available');
  assert.equal(await evaluate(`document.querySelector('[aria-label="ReShade 更新内置组件"]').disabled`), true);
  await click('[aria-label="wwmi-dx12 更新内置组件"]');
  await waitFor(`!document.querySelector('[aria-label="鸣潮 DX12 Mod"]').disabled && document.querySelector('[data-dx12-component="addon"]').textContent.includes('内置版本 2026.11.1')`, 'component update installed');
  assert.ok(fs.readFileSync(path.join(win64, 'wwmi_dx12.addon64')).includes(Buffer.from('smoke component update')));
  assert.equal((await call('wuwa:dx12-status')).enabled, true);
  await evaluate(`(() => { const pane = document.querySelector('.game-settings-view .system-settings-pane'), section = document.querySelector('#settings-wuwa-dx12'); pane.style.scrollBehavior = 'auto'; pane.scrollTop += section.getBoundingClientRect().top - pane.getBoundingClientRect().top; })()`);
  await captureUI('wuwa-dx12-managed.png');
  const requestCount = launchRequests.length;
  await click('[aria-label="启动游戏"]');
  await waitFor(`!document.querySelector('[aria-label="启动游戏"]').disabled`, 'DX12 launch request');
  assert.equal(launchRequests.length, requestCount + 1);
  assert.match(launchRequests.at(-1).file, /powershell.exe$/i);
  assert.ok(launchRequests.at(-1).args.some(arg => arg.endsWith('wuwa-dx12-launch.ps1')));
  // Exercise the actual Windows process launcher from Electron, not the UI's mock.
  // The isolated request has no game executable, so only the helper's failure path runs.
  const probe = path.join(root, 'DX12 helper probe'); fs.mkdirSync(probe);
  const probeEngine = path.join(probe, 'Engine.ini'), probeResult = path.join(probe, 'result.json'), probeRequest = path.join(probe, 'request.json');
  fs.writeFileSync(probeEngine, '[SystemSettings]');
  fs.writeFileSync(probeRequest, JSON.stringify({ gameRoot: probe, engine: probeEngine, resultFile: probeResult, arguments: '-dx12', engineReadOnly: false }));
  const helper = launchRequests.at(-1), nativeLauncher = require('../app/out/main/system/launch.cjs').createWindowsLauncher({ isElevated: () => true });
  const helperArgs = [...helper.args]; helperArgs[helperArgs.length - 1] = probeRequest;
  assert.equal((await nativeLauncher.launch(helper.file, helper.cwd, helperArgs, { requireElevation: false })).success, true);
  for (let i = 0; i < 50 && !fs.existsSync(probeResult); i++) await new Promise(resolve => setTimeout(resolve, 100));
  assert.ok(fs.existsSync(probeResult), 'PowerShell must execute the script and write a result');
  assert.equal(JSON.parse(fs.readFileSync(probeResult)).success, false);
  assert.equal(JSON.parse(fs.readFileSync(probeResult)).started, false);
  assert.ok(fs.statSync(probeEngine).mode & 0o200, 'helper restored the writable attribute after failure');
  passed('Native PowerShell helper executes from Electron and reports failures; DX12 selection is persisted to disk');
  assert.ok(fs.readFileSync(path.join(win64, 'wwmi_dx12.ini')).toString('utf16le').includes(wwmi));
  await click('[aria-label="XXMI 启动"]');
  await waitFor(`!document.querySelector('[aria-label="XXMI 启动"]').disabled`, 'XXMI UI still available');
  assert.deepEqual(launchRequests.at(-1).args, []);
  // A user-supplied replacement has no matching ownership hash and must survive disable.
  fs.appendFileSync(path.join(win64, 'dxgi.dll'), '\nuser replacement');
  await click('[aria-label="鸣潮 DX12 Mod"]');
  await waitFor(`!document.querySelector('[aria-label="鸣潮 DX12 Mod"]').checked && !document.querySelector('[aria-label="鸣潮 DX12 Mod"]').disabled`, 'DX12 deactivated');
  state = await call('wuwa:dx12-status');
  assert.equal(state.sources.reshade.source, 'user'); assert.equal(state.sources.addon.source, 'managed'); assert.equal(state.sources.addon.active, false);
  assert.ok(fs.readFileSync(path.join(win64, 'dxgi.dll')).includes(Buffer.from('user replacement')));
  assert.equal(fs.existsSync(path.join(win64, 'wwmi_dx12.addon64')), false);
  assert.match(await evaluate(`document.querySelector('[data-dx12-component="reshade"]').textContent`), /用户安装/);
  assert.match(await evaluate(`document.querySelector('[data-dx12-component="addon"]').textContent`), /已禁用/);
  await captureUI('wuwa-dx12-mixed.png');
  await click('[aria-label="启动游戏"]');
  await waitFor(`!document.querySelector('[aria-label="启动游戏"]').disabled`, 'WWMI route restored');
  assert.deepEqual(launchRequests.at(-1).args, ['--nogui', '--xxmi', 'WWMI']);
  passed('DX12 installs verified real packages, updates a simulated new release, labels ownership, routes direct launch, and preserves user replacements when disabled');
};
