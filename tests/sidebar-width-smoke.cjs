const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async ({ evaluate, waitFor, window, passed }) => {
  const width = () => evaluate(`Math.round(document.querySelector('.sidebar').getBoundingClientRect().width)`);
  await waitFor(`!!document.querySelector('.sidebar-resize-handle')`, 'sidebar resize handle');
  if (!window.webContents.debugger.isAttached()) window.webContents.debugger.attach('1.3');
  const point = await evaluate(`(() => { const r = document.querySelector('.sidebar-resize-handle').getBoundingClientRect(); return { x: r.right - 3, y: r.top + 140 }; })()`);
  const mouse = (type, x) => window.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type, x, y: point.y, button: 'left', buttons: type === 'mouseReleased' ? 0 : 1, clickCount: type === 'mouseMoved' ? 0 : 1 });
  await mouse('mousePressed', point.x);
  await mouse('mouseMoved', point.x + 180);
  await mouse('mouseReleased', point.x + 180);
  await waitFor(`localStorage.getItem('qaqm.sidebarWidth') === '320'`, 'maximum sidebar width saved');
  await waitFor(`Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 320`, 'resize rendered');
  assert.equal(await width(), 320);
  await evaluate(`document.querySelector('.game-selector-trigger').click()`);
  await waitFor(`!!document.querySelector('.game-selector-menu')`, 'game menu width comparison');
  assert.equal(await evaluate(`Math.round(document.querySelector('.game-selector-menu').getBoundingClientRect().width)`), await width());
  await evaluate(`document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))`);
  await evaluate(`document.documentElement.style.setProperty('--ui-scale', '1.4')`);
  await waitFor(`Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 320`, 'zoom width settled');
  assert.equal(await width(), 320, 'sidebar zoom cannot exceed the menu width');
  const [windowWidth, windowHeight] = window.getSize();
  window.setSize(1000, 640);
  assert.ok(await evaluate(`document.querySelector('.sidebar-header').getBoundingClientRect().top >= document.querySelector('.window-titlebar').getBoundingClientRect().bottom`), 'short-window styles keep scaled sidebar controls below the drag region');
  window.setSize(windowWidth, windowHeight);
  await evaluate(`document.documentElement.style.setProperty('--ui-scale', '1')`);
  await evaluate(`document.querySelector('.sidebar-resize-handle').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true }))`);
  await waitFor(`localStorage.getItem('qaqm.sidebarWidth') === '312'`, 'keyboard resize');
  await window.loadFile(path.join(process.resourcesPath, 'app/out/renderer/index.html'));
  await waitFor(`document.querySelector('.sidebar-resize-handle')?.getAttribute('aria-valuenow') === '312'`, 'width survives reload');
  const [surfaceWidth, surfaceHeight] = window.getSize();
  window.setSize(surfaceWidth + 1, surfaceHeight);
  window.setSize(surfaceWidth, surfaceHeight);
  assert.equal(await width(), 312);
  await evaluate(`document.querySelector('.sidebar-toggle').click()`);
  await waitFor(`!!document.querySelector('.sidebar.collapsed') && !document.querySelector('.sidebar-resize-handle')`, 'collapse hides width handle');
  assert.equal(await evaluate(`document.querySelector('.sidebar').getBoundingClientRect().top`), 0, 'collapsed sidebar also reaches the top edge');
  await evaluate(`document.querySelector('.sidebar-header').click()`);
  await waitFor(`!!document.querySelector('.sidebar:not(.collapsed) .sidebar-resize-handle')`, 'expand restores width');
  await waitFor(`Math.round(document.querySelector('.sidebar').getBoundingClientRect().width) === 312`, 'expanded width settled');
  assert.equal(await width(), 312);
  await evaluate(`document.querySelector('.sidebar-resize-handle').dispatchEvent(new MouseEvent('dblclick', { bubbles: true }))`);
  await waitFor(`localStorage.getItem('qaqm.sidebarWidth') === '240'`, 'reset width');
  passed('Sidebar width: native dragging, menu-width maximum, zoom, keyboard adjustment, persistence and collapse/expand');
};
