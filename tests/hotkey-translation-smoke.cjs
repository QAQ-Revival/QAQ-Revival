const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async function ({ electron, root, mods, passed }) {
  const { BrowserWindow, net } = electron;
  const names = ['belt', 'weist', 'cloth', 'gloves', 'hat', 'socks', 'wings', 'tail', 'bra', 'panty', 'swp_5a3faabb_help', 'swp_5a3faabb_zoom0', 'swp_5a3faabb_mouse_clicked'];
  const expected = ['腰带', '腰部', '衣服', '手套', '帽子', '袜子', '翅膀', '尾巴', '胸罩', '内裤', '帮助', '缩放', '鼠标点击'];
  const fixtureNames = names;
  const fixtureDir = path.join(mods, '安可', 'TFLS_DBL');
  fs.mkdirSync(fixtureDir, { recursive: true });
  const ini = fixtureNames.map((name, i) => `[Key${name}]\nkey = ${i === names.length - 1 ? 'VK_RBUTTON' : String.fromCharCode(65 + i)}\n`).join('\n');
  fs.writeFileSync(path.join(fixtureDir, 'mod.ini'), ini);
  let requests = [], fail = false, releaseRequest;
  net.fetch = async address => {
    const url = new URL(address);
    assert.equal(url.hostname, 'translate.googleapis.com');
    const name = url.searchParams.get('q');
    requests.push(name);
    if (name === 'delayed') await new Promise(resolve => { releaseRequest = resolve; });
    if (fail) throw Error('Synthetic offline');
    const queryNames = fixtureNames.map(name => name.replace(/^swp_[a-f\d]+_/, '').replace(/_/g, ' '));
    return new Response(JSON.stringify([[[expected[queryNames.indexOf(name)] || '译文', name]], null, 'en']));
  };
  const overlay = new BrowserWindow({ show: false, webPreferences: { preload: path.join(process.resourcesPath, 'overlay-preload.js'), sandbox: false, contextIsolation: true, offscreen: true } });
  await overlay.loadFile(path.join(process.resourcesPath, 'overlay.html'));
  const runOverlay = code => overlay.webContents.executeJavaScript(code, true);
  await runOverlay(`selectedChar = '安可'; currentMods = [{ name: 'TFLS_DBL', enabled: true }]; overlaySettings.clickableHotkeysEnabled = true; openDetail('TFLS_DBL')`);
  const side = BrowserWindow.getAllWindows().find(win => win.webContents.getURL().endsWith('/side-panel.html'));
  assert.ok(side);
  side.setSize(300, 950);
  const evaluate = code => side.webContents.executeJavaScript(code, true);
  const wait = async code => {
    for (let i = 0; i < 150; i++) {
      if (await evaluate(code)) return;
      await new Promise(resolve => setTimeout(resolve, 40));
    }
    throw Error('Timeout: ' + code);
  };
  const labels = () => evaluate(`[...document.querySelectorAll('.detail-hotkey-name')].map(el => el.textContent)`);
  const click = () => evaluate(`document.querySelector('#detailTranslateBtn').click()`);
  await wait(`document.querySelectorAll('.detail-hotkey-name').length === ${names.length}`);
  assert.equal(requests.length, 0);
  const originals = await labels();
  const bindings = await evaluate(`[...document.querySelectorAll('.detail-hotkey-row')].map(el => [el.dataset.hotkeyPayload, el.querySelector('.detail-hotkey-keys').textContent])`);
  const note = await evaluate(`document.querySelector('.detail-hotkey-note').textContent`);
  const html = await evaluate(`document.querySelector('#sideBody').innerHTML`);
  const data = { type: 'detail', title: 'TFLS_DBL', charName: '安可', modName: 'TFLS_DBL', gameId: 'wuthering-waves', html, clickableHotkeysEnabled: true };
  const content = async updates => { side.webContents.send('side-panel-content', { ...data, ...updates }); await wait(`!!document.querySelector('#detailTranslateBtn')`); await new Promise(resolve => setTimeout(resolve, 80)); };
  await click();
  await wait(`document.querySelector('#detailTranslateBtn').getAttribute('aria-pressed') === 'true'`);
  const translated = await labels();
  assert.deepEqual(new Set(translated), new Set(expected));
  assert.deepEqual(await evaluate(`[...document.querySelectorAll('.detail-hotkey-row')].map(el => [el.dataset.hotkeyPayload, el.querySelector('.detail-hotkey-keys').textContent])`), bindings);
  assert.equal(await evaluate(`document.querySelector('.detail-hotkey-note').textContent`), note);
  assert.deepEqual(await evaluate(`[...document.querySelectorAll('.detail-hotkey-name')].map(el => el.title)`), originals);
  const count = requests.length;
  await side.loadFile(path.join(process.resourcesPath, 'side-panel.html'));
  await content({});
  assert.deepEqual(await labels(), translated);
  assert.equal(requests.length, count, 'Reload restores cached translation without network');
  await evaluate(`document.querySelector('#sideBody').scrollTop = 0`);
  fs.writeFileSync(path.join(root, 'hotkey-translation.png'), (await side.webContents.capturePage()).toPNG());
  for (const width of [200, 300, 550]) {
    side.setSize(width, 950);
    assert.equal(await evaluate(`document.querySelector('#sideBody').scrollWidth <= document.querySelector('#sideBody').clientWidth`), true, 'no horizontal overflow at ' + width);
  }
  await content({ gameId: 'zzz' });
  assert.deepEqual(await labels(), originals, 'Other game has its own switch');
  await content({ modName: 'OtherMod' });
  assert.deepEqual(await labels(), originals, 'Other Mod has its own switch');
  await content({ charName: '今汐' });
  assert.deepEqual(await labels(), originals, 'Other character has its own switch');
  await content({});
  await click();
  assert.deepEqual(await labels(), originals);
  await side.loadFile(path.join(process.resourcesPath, 'side-panel.html'));
  await content({});
  assert.deepEqual(await labels(), originals, 'Disabled switch also survives reload');
  await click();
  await content({ html: html.replace(/>belt</g, '>replacement_belt<') });
  await wait(`document.querySelector('#detailTranslateBtn').getAttribute('aria-pressed') === 'true'`);
  assert.ok(requests.includes('replacement belt'), 'Changed labels are retranslated for an enabled Mod');
  await content({});
  await wait(`document.querySelector('#detailTranslateBtn').getAttribute('aria-pressed') === 'true'`);
  passed('Real overlay/preload/IPC: Google labels, original names, key bindings, game/character/Mod persistence and 200–550 px layouts');

  const failHtml = html.replace(/>belt</g, '>network_failure<');
  await content({ html: failHtml, modName: 'FailureMod' });
  fail = true;
  await click();
  await wait(`document.querySelector('#detailTranslateBtn').textContent === '重试翻译'`);
  assert.equal(await evaluate(`document.querySelector('#detailTranslateBtn').disabled`), false);
  fail = false;
  await click();
  await wait(`document.querySelector('#detailTranslateBtn').getAttribute('aria-pressed') === 'true'`);
  await content({ html: html.replace(/>belt</g, '>delayed<'), modName: 'DelayedMod' });
  await click();
  await wait(`document.querySelector('#detailTranslateBtn').disabled`);
  while (!releaseRequest) await new Promise(resolve => setTimeout(resolve, 10));
  await content({ modName: 'OtherMod' });
  releaseRequest();
  await new Promise(resolve => setTimeout(resolve, 150));
  assert.deepEqual(await labels(), originals, 'Late translation does not affect a different Mod');
  assert.equal(await evaluate(`localStorage.getItem('hotkey-translation:v1:' + JSON.stringify(['wuthering-waves', '安可', 'DelayedMod']))`), null);
  await content({ html: html.replace(/<div class="detail-hotkey-section">[\s\S]*?<button class="detail-toggle-btn /, '<div class="detail-hotkey-section">无快捷键</div><button class="detail-toggle-btn '), modName: 'EmptyMod' });
  assert.equal(await evaluate(`document.querySelector('#detailTranslateBtn').disabled`), true);
  assert.equal(fs.readFileSync(path.join(fixtureDir, 'mod.ini'), 'utf8'), ini);
  passed('Translation failure/retry, stale response isolation, empty list and unchanged Mod INI');
  side.webContents.session.flushStorageData();
  side.destroy(); overlay.destroy();
};
