const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

module.exports = async ({ electron, evaluate, waitFor, captureUI, handlers, root, profile, passed, launchRequests, selectNativeAction }) => {
  const call = (name, ...args) => handlers.get(name)({}, ...args);
  const click = selector => evaluate(`document.querySelector(${JSON.stringify(selector)}).click()`);
  const png = electron.nativeImage.createFromBitmap(Buffer.from([0x70, 0x90, 0xe0, 0xff]), { width: 1, height: 1 }).toPNG();
  const game = (await call('game:list')).games.find(item => item.id === 'arknights');
  assert.equal(game.launchMode, 'ARKNIGHTS');
  assert.equal(game.modFolderPath, path.join(root, 'data/Arknights/Mods'));
  const source = path.join(root, 'arknights-pc');
  fs.mkdirSync(source);
  fs.writeFileSync(path.join(source, 'illust_char_4215_buddy_mh_2.png'), png);
  await call('game:switch', 'arknights');
  await waitFor(`document.querySelector('.game-selector-trigger')?.textContent.includes('明日方舟')`, 'Arknights selected');
  assert.equal(await evaluate(`document.querySelector('.launch-button-direct')?.getAttribute('aria-label')`), '启动游戏');
  assert.equal(await evaluate(`document.querySelector('.launch-button-direct')?.textContent.trim()`), '启动游戏');
  const characters = await call('get-characters');
  assert(characters.characters.some(item => item.name === '罗德岛隐秘队'), JSON.stringify(characters).slice(0, 2000));
  assert(characters.characters.length > 400);
  const imported = await call('add-mod', { characterName: '艾露猫', filePath: source, modInfo: { name: 'PC sample' } });
  assert.equal(imported.success, true, JSON.stringify(imported));
  let mods = await call('get-mods', '艾露猫');
  assert.equal(mods.mods[0].enabled, false);
  assert(mods.mods[0].previewUrl);
  const toggle = await call('toggle-mod', { characterName: '艾露猫', modName: 'PC sample', enable: true });
  assert.equal(toggle.success, true, JSON.stringify(toggle));
  let state = await call('arknights:status');
  assert.equal(state.singleModReloadSupported, true);
  assert.equal(state.sync.modCount, 1);
  assert.equal(state.sync.fileCount, 1);
  const conflictingSource = path.join(root, 'arknights-conflicting');
  fs.mkdirSync(conflictingSource);
  fs.writeFileSync(path.join(conflictingSource, 'illust_char_4215_buddy_mh_2.png'), electron.nativeImage.createFromBitmap(Buffer.from([0xff, 0x10, 0x20, 0xff]), { width: 1, height: 1 }).toPNG());
  const second = await call('add-mod', { characterName: '艾露猫', filePath: conflictingSource, modInfo: { name: 'conflict' } });
  assert.equal(second.success, true);
  const conflict = await call('toggle-mod', { characterName: '艾露猫', modName: 'conflict', enable: true });
  assert.equal(conflict.pending, true);
  assert.equal((await call('get-mods', '艾露猫')).mods.find(mod => mod.name === 'conflict').enabled, false);
  assert.equal((await call('overlay-get-mods', '艾露猫')).mods.find(mod => mod.name === 'conflict').pendingEnabled, true);
  assert.equal((await call('arknights:status')).sync.modCount, 1);
  const confirmed = await call('confirm-mod-conflicts', { characterName: '艾露猫', overlay: true });
  assert.equal(confirmed.success, true, JSON.stringify(confirmed));
  assert.equal((await call('arknights:status')).sync.modCount, 2);
  assert.equal((await call('toggle-mod', { characterName: '艾露猫', modName: 'conflict', enable: false })).success, true);
  passed('Arknights imports start disabled; main and overlay share pending conflicts, with no deployment until explicit confirmation');

  const bundleSource = path.join(root, 'arknights-bundle');
  fs.mkdirSync(bundleSource);
  fs.writeFileSync(path.join(bundleSource, 'char_4215_buddy.ab'), 'UnityFS');
  assert.equal((await call('add-mod', { characterName: '艾露猫', filePath: bundleSource, modInfo: { name: 'mobile pending' } })).success, true);
  assert.equal((await call('get-mods', '艾露猫')).mods.find(mod => mod.name === 'mobile pending').appearanceSectionId, 'arknights:shared');
  assert((await call('toggle-mod', { characterName: '艾露猫', modName: 'mobile pending', enable: true })).error);
  assert.equal((await call('toggle-mod', { characterName: '艾露猫', modName: 'PC sample', enable: false })).success, true);
  assert.equal((await call('arknights:status')).sync.modCount, 0);
  assert.equal((await call('overlay-toggle-mod', { characterName: '艾露猫', modName: 'PC sample', enabled: true })).success, true);
  assert.equal((await call('arknights:status')).sync.modCount, 1);
  assert.equal((await call('overlay-toggle-mod', { characterName: '艾露猫', modName: 'PC sample', enabled: false })).success, true);
  assert.equal((await call('arknights:status')).sync.modCount, 0);
  const { createRequire } = require('node:module');
  const runtimeRequire = createRequire(path.join(process.resourcesPath, 'app/package.json'));
  const presets = runtimeRequire('./out/main/presets/service.cjs');
  const applied = await presets.applyPresetModsForGame({ mods: [{ characterName: '艾露猫', modName: 'PC sample' }] }, 'arknights');
  assert.equal(applied.success, true); presets.notifyPresetApplicationChanged('arknights');
  assert.equal((await call('arknights:status')).sync.modCount, 1);
  const hidden = await call('character:set-hidden', { characterName: '艾露猫', hidden: true, gameId: 'arknights' });
  assert.equal(hidden.success, true, JSON.stringify(hidden));
  assert.equal((await call('arknights:status')).sync.modCount, 0);
  assert.equal((await call('character:set-hidden', { characterName: '艾露猫', hidden: false, gameId: 'arknights' })).success, true);
  passed('Raw bundles are blocked until conversion; disabling, applying a preset and hiding an operator update the external M4A directory');

  await evaluate(`window.dispatchEvent(new CustomEvent('qaqm-navigate', { detail: { tab: 'characters', characterName: '艾露猫' } }))`);
  // Open through the actual character card to exercise the normal manager route.
  await waitFor(`[...document.querySelectorAll('.character-card')].some(card => card.textContent.includes('罗德岛隐秘队'))`, 'operator card');
  await evaluate(`[...document.querySelectorAll('.character-card')].find(card => card.textContent.includes('罗德岛隐秘队')).click()`);
  await waitFor(`!!document.querySelector('.arknights-library-notice') && !!document.querySelector('.mod-view-container')`, 'M4A Mod library');
  await waitFor(`[...document.querySelectorAll('button')].some(button => button.textContent.includes('跨皮肤'))`, 'appearance sections loaded');
  assert.equal(await evaluate(`[...document.querySelectorAll('button')].some(button => button.textContent.includes('跨皮肤'))`), true);
  await evaluate(`[...document.querySelectorAll('button')].find(button => button.textContent.includes('露营时间喵'))?.click()`);
  await waitFor(`!!document.querySelector('[data-mod-name="PC sample"]')`, 'skin-specific Mod');
  assert.equal(await evaluate(`document.querySelector('.mod-view-titlebar-actions button').classList.contains('active')`), false);
  assert.equal(await evaluate(`document.querySelector('[data-mod-name="PC sample"] .mod-type-badge').textContent`), '皮肤 · 静态');
  assert.equal(await evaluate(`document.querySelectorAll('[data-mod-name] .mod-row-tag-row').length`), 0);
  assert.equal(await evaluate(`!!document.querySelector('.mod-sort-bar .mod-tag-filter')`), true);
  await captureUI('arknights-library.png');
  const overlay = new electron.BrowserWindow({ show: false, webPreferences: { preload: path.join(process.resourcesPath, 'app/out/preload/overlay.js'), sandbox: false, contextIsolation: true, offscreen: true } });
  const runOverlay = code => overlay.webContents.executeJavaScript(code, true);
  async function overlayWait(code) {
    for (let attempt = 0; attempt < 150; attempt++) { if (await runOverlay(code)) return; await new Promise(resolve => setTimeout(resolve, 40)); }
    throw Error('Overlay timeout: ' + code);
  }
  try {
    await overlay.loadFile(path.join(process.resourcesPath, 'app/out/renderer/overlay/index.html'));
    await overlayWait(`!!document.querySelector('.char-chip[data-name="罗德岛隐秘队"]')`);
    await runOverlay(`document.querySelector('.char-chip[data-name="罗德岛隐秘队"]').click()`);
    await overlayWait(`document.querySelectorAll('#appearanceSections [role="tab"]').length > 1`);
    assert.equal(await runOverlay(`document.querySelector('#exclusiveBtn').classList.contains('active')`), false);
    await runOverlay(`[...document.querySelectorAll('#appearanceSections button')].find(button => button.textContent.includes('跨皮肤')).click()`);
    await waitFor(`document.querySelector('.appearance-section-tab.active')?.textContent.includes('跨皮肤')`, 'skin tab synchronization from overlay');
    await runOverlay(`[...document.querySelectorAll('#appearanceSections button')].find(button => button.textContent.includes('露营时间喵')).click()`);
    await overlayWait(`!!document.querySelector('[data-toggle="1"][data-mod="PC sample"]')`);
    assert.equal(await runOverlay(`document.querySelector('[data-mod="PC sample"] .mod-type-badge').textContent`), '皮肤 · 静态');
    await runOverlay(`document.querySelector('[data-toggle="1"][data-mod="PC sample"]').click()`);
    await overlayWait(`document.querySelector('[data-toggle="1"][data-mod="PC sample"]')?.dataset.enabled === 'true'`);
    await runOverlay(`document.querySelector('[data-toggle="1"][data-mod="conflict"]').click()`);
    await overlayWait(`!document.querySelector('#conflictConfirm').hidden`);
    assert.equal((await call('get-mods', '艾露猫')).mods.find(mod => mod.name === 'conflict').enabled, false);
    assert.equal(await runOverlay(`document.querySelector('#toast').textContent`), 'MOD冲突，请确认');
    await waitFor(`!!document.querySelector('.mod-conflict-confirm')`, 'main sees overlay pending conflict');
    await captureUI('arknights-pending-conflict.png');
    await runOverlay(`document.querySelector('#conflictConfirm button').click()`);
    await overlayWait(`document.querySelector('#conflictConfirm').hidden`);
    assert.equal((await call('get-mods', '艾露猫')).mods.filter(mod => mod.enabled).length, 2);
    fs.writeFileSync(path.join(root, 'arknights-overlay.png'), (await overlay.webContents.capturePage()).toPNG());
    await runOverlay(`document.querySelector('#bubbleToggleBtn').click()`);
    let side;
    for (let attempt = 0; attempt < 150; attempt++) { side = electron.BrowserWindow.getAllWindows().find(win => win.webContents.getURL().endsWith('/side-panel.html')); if (side && await side.webContents.executeJavaScript(`!!document.querySelector('.bubble-avatar')`)) break; await new Promise(resolve => setTimeout(resolve, 40)); }
    assert.ok(side);
    const visible = await side.webContents.executeJavaScript(`(() => { const input = document.querySelector('#sideCharacterSearch'); input.value = 'luodedao'; input.dispatchEvent(new Event('input')); return [...document.querySelectorAll('.bubble-avatar:not([hidden])')].map(el => el.dataset.name); })()`);
    assert.deepEqual(visible, ['罗德岛隐秘队']);
    await new Promise(resolve => setTimeout(resolve, 250));
    fs.writeFileSync(path.join(root, 'arknights-overlay-search.png'), (await side.webContents.capturePage()).toPNG());
    side.hide();
    await call('toggle-mod', { characterName: '艾露猫', modName: 'conflict', enable: false });
    await call('toggle-mod', { characterName: '艾露猫', modName: 'PC sample', enable: false });
    passed('Overlay skin tabs, type badges, pinyin character search and conflict confirmation work and synchronize with the main window');
  } finally { overlay.destroy(); }
  await evaluate(`document.querySelector('[data-mod-name="PC sample"]').dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 480, clientY: 330 }))`);
  await waitFor(`[...document.querySelectorAll('.mod-context-menu button')].some(button => button.textContent.includes('诊断'))`, 'M4A context tools');
  assert.equal(await evaluate(`[...document.querySelectorAll('.mod-context-menu button')].some(button => button.textContent === '重载此 MOD')`), true);
  await evaluate(`[...document.querySelectorAll('.mod-context-menu button')].find(button => button.textContent === '重载此 MOD').click()`);
  await waitFor(`document.querySelector('.toast-error')?.textContent.includes('QAQR')`, 'reload requires a connected game runtime');
  assert.equal(await evaluate(`!!document.querySelector('.mod-context-menu')`), false);
  await evaluate(`document.querySelector('[data-mod-name="PC sample"]').dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: 480, clientY: 330 }))`);
  await waitFor(`!!document.querySelector('.mod-context-menu')`, 'context menu after reload');
  await evaluate(`[...document.querySelectorAll('.mod-context-menu button')].find(button => button.textContent.includes('诊断')).click()`);
  await waitFor(`!!document.querySelector('.arknights-plan')`, 'actual worker diagnosis');
  await captureUI('arknights-diagnosis.png');
  await evaluate(`[...document.querySelectorAll('.arknights-dialog button')].find(button => button.textContent.includes('生成修复副本')).click()`);
  await waitFor(`!!document.querySelector('.arknights-result')`, 'create copy');
  mods = await call('get-mods', '艾露猫');
  assert(mods.mods.some(mod => /Repaired/.test(mod.name) && !mod.enabled));
  assert.deepEqual(fs.readFileSync(path.join(source, 'illust_char_4215_buddy_mh_2.png')), png);
  await click('.arknights-dialog-heading button');
  await click('.game-settings-button');
  await waitFor(`!!document.querySelector('#settings-arknights-tools')`, 'M4A settings');
  await waitFor(`!!document.querySelector('#settings-arknights-cursor [role="switch"]')`, 'system cursor setting');
  assert.equal(await evaluate(`document.querySelector('#settings-arknights-cursor [role="switch"]').getAttribute('aria-label')`), '使用系统光标');
  assert.equal(await evaluate(`document.querySelector('#heading-arknights-tools').textContent`), '加载器');
  await captureUI('arknights-settings.png');
  assert.equal(await evaluate(`!!document.querySelector('#settings-game-persist, #settings-fixer')`), false);
  assert.equal(launchRequests.length, 0, 'No game or loader launches are permitted in this smoke scope');
  passed('Actual renderer context menu runs the offline worker and creates a disabled copy without changing its source; M4A settings render without XXMI controls; no game is launched');
  await require('./library-performance-smoke.cjs')({ electron, evaluate, waitFor, captureUI, handlers, root, passed, selectNativeAction });
  if (process.env.QAQR_ARKNIGHTS_GAME_EXE && process.env.QAQR_ARKNIGHTS_MOBILE_ZIP && process.env.QAQR_ARKNIGHTS_PC_ZIP) {
    const crypto = require('node:crypto');
    const hash = file => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
    const gamePath = process.env.QAQR_ARKNIGHTS_GAME_EXE;
    const protectedFiles = [gamePath, path.join(path.dirname(gamePath), 'Arknights_Data/StreamingAssets/AB/Windows/skinpack/char_4215_buddy.ab'), process.env.QAQR_ARKNIGHTS_MOBILE_ZIP, process.env.QAQR_ARKNIGHTS_PC_ZIP];
    const before = protectedFiles.map(hash);
    assert.equal((await call('game:update', { gameId: 'arknights', updates: { gamePath } })).success, true);
    const reports = [];
    for (const [name, filePath, expected] of [['Mobile attachment', process.env.QAQR_ARKNIGHTS_MOBILE_ZIP, 10], ['PC attachment', process.env.QAQR_ARKNIGHTS_PC_ZIP, 1]]) {
      const imported = await call('add-mod', { characterName: '艾露猫', filePath, modInfo: { name } });
      assert.equal(imported.success, true, JSON.stringify(imported));
      const analysis = await call('arknights:analyze', { characterName: '艾露猫', modName: name });
      assert.equal(analysis.success, true, JSON.stringify(analysis));
      assert.equal(analysis.plans.length, expected); assert.equal(analysis.matched, expected);
      if (expected === 1) assert.equal(analysis.renamed, 1);
      const copy = await call('arknights:create-copy', { token: analysis.token, selectedIds: analysis.plans.map(plan => plan.id) });
      assert.equal(copy.success, true, JSON.stringify(copy));
      assert.equal((await call('get-mods', '艾露猫')).mods.find(mod => mod.name === copy.modName).enabled, false);
      reports.push({ name, count: copy.count, path: copy.path, plans: analysis.plans, warnings: analysis.warnings });
    }
    const converted = (await call('get-mods', '艾露猫')).mods.find(mod => mod.name === 'Mobile attachment (PC)');
    assert(converted);
    assert.equal((await call('toggle-mod', { characterName: '艾露猫', modName: converted.name, enable: true })).success, true);
    const prepared = await call('arknights:prepare-loader');
    assert.equal(prepared.success, true, JSON.stringify(prepared));
    assert.equal(prepared.resourceCount, 10);
    assert.equal(prepared.bundleCount, 1);
    const component = await call('arknights:status');
    assert.match(component.loader, /ArkLoader\.exe$/);
    assert.equal(component.source, 'https://github.com/QAQ-Revival/Arknights-Mod-Tools');
    assert.equal(component.experimental, true);
    assert.equal(handlers.has('arknights:select-loader'), false);
    assert.deepEqual(protectedFiles.map(hash), before);
    assert.equal(launchRequests.length, 0);
    fs.writeFileSync(path.join(root, 'arknights-samples.json'), JSON.stringify(reports, null, 2));
    passed('Both supplied archives converted; the source-built worker rebuilt 10 resources into a verified external PC bundle, and the source-built loader checked it without starting the game; original files retain identical SHA-256');
  }
};
