const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');

module.exports = async ({ evaluate, waitFor, captureUI, window, root, profile, mods, handlers, passed, nativeMenus, selectNativeAction }) => {
  const call = (name, ...args) => handlers.get(name)({}, ...args);
  const fixture = (relative, text = '[TextureOverrideTest]\nhash = 12345678\n') => {
    const file = path.join(mods, relative);
    fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text);
  };
  const clickText = text => evaluate(`[...document.querySelectorAll('button')].find(button => button.textContent.trim() === ${JSON.stringify(text)}).click()`);
  const card = `document.querySelector('.character-card[aria-label^="安可，"]')`;
  fixture('安可/Active A/mod.ini'); fixture('安可/Active B/mod.ini'); fixture('Encore/AliasMod/mod.ini');
  fixture('安可/info.json', '{"name":"安可","description":"keep me"}');
  const preset = await call('preset:create', { name: 'Hidden character regression', mods: [{ characterName: '安可', modName: 'Active A', enabled: true }] });
  assert.equal(preset.success, true);
  await clickText('刷新');
  await waitFor(`!!${card}`, 'character available');
  selectNativeAction('pin');
  await evaluate(`${card}.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true, clientX: innerWidth - 2, clientY: innerHeight - 2 }))`);
  await waitFor(`!!${card}.querySelector('.character-pin-badge')`, 'native menu pin action');
  assert.equal(nativeMenus.at(-1).options.window, window);
  assert.equal('x' in nativeMenus.at(-1).options, false, 'Native menu uses screen cursor placement');
  assert.ok(nativeMenus.at(-1).menu.items.every(item => !item.label.includes('隐藏')));
  assert.equal(await evaluate(`!!document.querySelector('.character-context-menu')`), false);
  await evaluate(`${card}.dispatchEvent(new MouseEvent('contextmenu', { bubbles: true }))`);
  await evaluate('new Promise(resolve => setTimeout(resolve, 100))');
  assert.equal(nativeMenus.at(-1).menu.getMenuItemById('pin').label, '取消置顶');
  const placement = await evaluate(`(() => {
    const card = ${card}; card.querySelector('.hide-character-btn').focus();
    const hide = card.querySelector('.hide-character-btn').getBoundingClientRect();
    const remove = card.querySelector('.delete-btn').getBoundingClientRect();
    return { beside: hide.right < remove.left, aligned: hide.top === remove.top };
  })()`);
  assert.deepEqual(placement, { beside: true, aligned: true });
  await captureUI('character-card-actions.png');
  passed('Character menu uses the native OS popup at the screen cursor; pin/cancel work; hide button sits left of delete and is absent from the menu');
  await evaluate(`${card}.querySelector('.hide-character-btn').click()`);
  await waitFor(`!${card} && document.body.textContent.includes('已隐藏「安可」')`, 'hide completion');
  for (const relative of ['安可/DISABLED_Active A/mod.ini', '安可/DISABLED_Active B/mod.ini', 'Encore/DISABLED_AliasMod/mod.ini', '安可/DISABLED_测试模组/mod.ini']) assert.ok(fs.existsSync(path.join(mods, relative)), relative);
  assert.equal(fs.readFileSync(path.join(mods, '安可/info.json'), 'utf8'), '{"name":"安可","description":"keep me"}');
  assert.ok(!(await call('get-characters')).characters.some(item => item.name === '安可'));
  assert.ok(!(await call('overlay-get-characters')).characters.some(item => item.name === '安可'));
  assert.deepEqual((await call('character:list-hidden', 'wuthering-waves')).characters.map(item => item.name), ['安可']);
  assert.deepEqual((await call('character:list-hidden', 'endfield')).characters, []);
  assert.match((await call('toggle-mod', { characterName: '安可', modName: 'Active A', enable: true })).error, /隐藏/);
  assert.match((await call('overlay-toggle-mod', { characterName: 'Encore', modName: 'Active A', enabled: true })).error, /隐藏/);
  assert.equal((await call('preset:activate', preset.preset.id)).success, true);
  assert.equal(fs.existsSync(path.join(mods, '安可/Active A')), false);
  assert.equal((await call('character:update-catalog', 'wuthering-waves')).success, true);
  assert.ok(!(await call('character:refresh')).characters.some(item => item.name === '安可'));
  assert.ok(JSON.parse(fs.readFileSync(path.join(profile, 'config.json'))).hiddenCharactersByGame['wuthering-waves'].includes('安可'));
  passed('Hide action disables every Mod including alias folders, preserves files, filters manager/overlay and survives catalog refresh; presets cannot re-enable hidden Mods');

  // The profile is read again by the real renderer on reload.
  await window.loadFile(path.join(process.resourcesPath, 'app/out/renderer/index.html'));
  await waitFor(`!!document.querySelector('.character-toolbar-actions')`, 'renderer reload');
  assert.equal(await evaluate(`!!${card}`), false);
  await clickText('隐藏角色 (1)');
  await waitFor(`!!document.querySelector('[aria-label="恢复显示 安可"]')`, 'hidden manager');
  const [surfaceWidth, surfaceHeight] = window.getSize();
  window.setSize(surfaceWidth + 1, surfaceHeight);
  window.setSize(surfaceWidth, surfaceHeight);
  await captureUI('hidden-characters.png');
  await evaluate(`document.querySelector('[aria-label="恢复显示 安可"]').click()`);
  await waitFor(`document.querySelector('.hidden-characters-empty')?.textContent.includes('暂无隐藏角色')`, 'restore from management');
  await evaluate(`document.querySelector('[aria-label="关闭隐藏角色"]').click()`);
  await waitFor(`!!${card}`, 'restored character visible');
  assert.equal((await call('get-characters')).characters.find(item => item.name === '安可').enabledCount, 0);
  assert.equal(fs.existsSync(path.join(mods, '安可/Active A')), false);
  passed('Hidden character management restores visibility without enabling Mods; count, empty state and renderer reload verified');

  fixture('安可/Conflict/mod.ini', 'enabled copy'); fixture('安可/DISABLED_Conflict/mod.ini', 'disabled copy'); fixture('安可/BeforeConflict/mod.ini');
  const result = await call('character:set-hidden', { characterName: '安可', hidden: true, gameId: 'wuthering-waves' });
  assert.equal(result.success, false);
  assert.match(result.error, /目标已存在/);
  assert.ok((await call('get-characters')).characters.some(item => item.name === '安可'));
  assert.ok(fs.existsSync(path.join(mods, '安可/BeforeConflict/mod.ini')));
  assert.equal(fs.readFileSync(path.join(mods, '安可/Conflict/mod.ini'), 'utf8'), 'enabled copy');
  assert.equal(fs.readFileSync(path.join(mods, '安可/DISABLED_Conflict/mod.ini'), 'utf8'), 'disabled copy');
  assert.equal((await call('character:set-hidden', { characterName: '../escape', hidden: true })).success, false);
  assert.equal((await call('character:set-hidden', { characterName: '安可', hidden: 'yes' })).success, false);
  const otherGame = await call('character:set-hidden', { characterName: '安可', hidden: true, gameId: 'endfield' });
  assert.equal(otherGame.success, true);
  assert.ok((await call('get-characters')).characters.some(item => item.name === '安可'));
  assert.equal((await call('character:set-hidden', { characterName: '女主', hidden: true, gameId: 'wuthering-waves' })).success, true);
  const emptyDir = path.join(mods, '女主');
  if (fs.readdirSync(emptyDir).length === 0) fs.rmdirSync(emptyDir);
  await call('character:update-catalog', 'wuthering-waves');
  assert.equal(fs.existsSync(emptyDir), false, 'Updating does not recreate a missing hidden default directory');
  passed('Conflict leaves character visible and all Mod bytes intact; invalid input rejected; per-game state and hidden default folder recreation tested');

  const nteRoot = path.join(root, 'nte-game');
  const nteMods = path.join(root, 'nte-mods');
  const disabled = path.join(root, 'nte-disabled');
  const launcher = path.join(nteRoot, 'NTELauncher.exe');
  fs.mkdirSync(nteRoot, { recursive: true }); fs.writeFileSync(launcher, 'test fixture');
  const pakDir = path.join(nteRoot, 'Client/WindowsNoEditor/HT/Content/Paks/MOD/薄荷/PakMod');
  const standardDir = path.join(nteMods, '薄荷/StandardMod');
  fs.mkdirSync(pakDir, { recursive: true }); fs.writeFileSync(path.join(pakDir, 'test.pak'), 'pak fixture');
  fs.writeFileSync(path.join(pakDir, 'test.ucas'), 'ucas fixture'); fs.writeFileSync(path.join(pakDir, 'test.utoc'), 'utoc fixture');
  fs.mkdirSync(standardDir, { recursive: true }); fs.writeFileSync(path.join(standardDir, 'mod.ini'), 'standard fixture');
  const configured = await call('game:get-settings', 'neverness-to-everness');
  assert.equal(configured.game.modFolderPath, nteMods);
  const hiddenNte = await call('character:set-hidden', { characterName: '薄荷', hidden: true, gameId: 'neverness-to-everness' });
  assert.equal(hiddenNte.success, true, hiddenNte.error);
  assert.equal(hiddenNte.disabledCount, 2);
  assert.equal(fs.readFileSync(path.join(disabled, '薄荷/PakMod/test.pak'), 'utf8'), 'pak fixture');
  assert.equal(fs.existsSync(pakDir), false);
  assert.equal(fs.readFileSync(path.join(nteMods, '薄荷/DISABLED_StandardMod/mod.ini'), 'utf8'), 'standard fixture');
  passed('Hiding an NTE character disables both standard Mods and Pak Mods even while another game is active');
};
