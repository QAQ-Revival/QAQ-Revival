const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { createRequire } = require('node:module');

module.exports = async ({ electron, evaluate, waitFor, captureUI, window, mods, handlers, passed }) => {
  const name = '多图预览';
  const dir = path.join(mods, '安可', 'DISABLED_' + name);
  fs.mkdirSync(path.join(dir, '画廊'), { recursive: true });
  fs.writeFileSync(path.join(dir, 'mod.ini'), '[TextureOverridePreviewFixture]\nhash = 12345678\n');
  const files = [['preview.png', 320, 240, 100], ['第二张.png', 640, 360, 165], ['画廊/第三张 #.png', 480, 800, 210]];
  const originals = new Map();
  for (const [file, width, height, shade] of files) {
    const bytes = electron.nativeImage.createFromBitmap(Buffer.alloc(width * height * 4, shade), { width, height }).toPNG();
    fs.writeFileSync(path.join(dir, file), bytes); originals.set(file, bytes);
  }
  const single = path.join(mods, '安可', 'DISABLED_单图预览');
  fs.mkdirSync(single, { recursive: true }); fs.writeFileSync(path.join(single, 'preview.png'), originals.get('preview.png'));
  fs.writeFileSync(path.join(single, 'mod.ini'), '[TextureOverrideSingle]\nhash = 11111111\n');
  await evaluate(`[...document.querySelectorAll('button')].find(button => button.textContent.trim() === '刷新').click()`);
  await waitFor(`!!document.querySelector('.character-card[aria-label^="安可，"]')`, 'preview character');
  await evaluate(`document.querySelector('.character-card[aria-label^="安可，"]').click()`);
  await waitFor(`!!document.querySelector('.mod-view-container')`, 'Mod view');
  if (await evaluate(`!!document.querySelector('.view-mode-gallery')`)) await evaluate(`document.querySelector('.view-mode-toggle').click()`);
  const row = `.mod-row[data-mod-name="${name}"]`;
  await waitFor(`!!document.querySelector(${JSON.stringify(row)})`, 'multi-image Mod');
  await evaluate(`document.querySelector(${JSON.stringify(row)}).click()`);
  const image = `document.querySelector('.mod-detail-preview img')`;
  await waitFor(`${image}?.naturalWidth === 320 && document.querySelector('.mod-preview-counter')?.textContent === '1 / 3'`, 'initial image and count');
  await captureUI('mod-preview-initial.png');
  window.webContents.debugger.attach('1.3');
  await window.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 1, y: 1 });
  await waitFor(`getComputedStyle(document.querySelector('.mod-preview-arrow.next')).opacity === '0'`, 'arrows hidden away from preview');
  const point = await evaluate(`(() => { const r = document.querySelector('.mod-detail-preview').getBoundingClientRect(); return { x: Math.round(r.x + r.width / 2), y: Math.round(r.y + r.height / 2) }; })()`);
  await window.webContents.debugger.sendCommand('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point });
  await waitFor(`getComputedStyle(document.querySelector('.mod-preview-arrow.next')).opacity === '1'`, 'hover reveals arrows');
  window.webContents.debugger.detach();
  await captureUI('mod-preview-hover.png');
  await evaluate(`document.querySelector('.mod-detail-preview .mod-preview-arrow.next').click()`);
  await waitFor(`${image}?.naturalWidth === 640 && document.querySelector(${JSON.stringify(row + ' img')})?.src === ${image}?.src`, 'next image updates list icon immediately');
  const choice = () => JSON.parse(fs.readFileSync(path.join(dir, '.qaqr-preview.json'), 'utf8')).image;
  await waitFor(`document.querySelector('.mod-preview-counter')?.textContent === '2 / 3'`, 'second image count');
  assert.equal(choice(), '第二张.png');
  await evaluate(`document.querySelector('.mod-detail-preview .mod-preview-arrow.next').click(); document.querySelector('.mod-detail-preview .mod-preview-arrow.next').click()`);
  await waitFor(`${image}?.naturalWidth === 320 && document.querySelector('.mod-preview-counter')?.textContent === '1 / 3'`, 'rapid clicks wrap to the latest choice');
  await evaluate(`document.querySelector('.mod-detail-preview .mod-preview-arrow.previous').click()`);
  await waitFor(`${image}?.naturalHeight === 800`, 'previous wraps to nested image');
  assert.equal(choice(), '画廊/第三张 #.png');
  await evaluate(`${image}.click()`);
  await waitFor(`!!document.querySelector('.mod-view-preview-lightbox .mod-preview-arrow.next')`, 'lightbox arrows');
  await evaluate(`document.querySelector('.mod-view-preview-lightbox .mod-preview-arrow.next').click()`);
  await waitFor(`document.querySelector('.mod-view-lightbox-image')?.naturalWidth === 320`, 'lightbox can cycle without closing');
  await evaluate(`document.querySelector('.mod-view-preview-lightbox .mod-preview-arrow.previous').click()`);
  await waitFor(`document.querySelector('.mod-view-lightbox-image')?.naturalHeight === 800`, 'lightbox returns to remembered image');
  await evaluate(`document.querySelector('.mod-view-preview-lightbox').click(); document.querySelector('.view-mode-toggle').click()`);
  await waitFor(`document.querySelector('.mod-gallery-card[data-mod-name="${name}"] img')?.src === ${image}?.src`, 'gallery thumbnail matches');
  await window.loadFile(path.join(process.resourcesPath, 'app/out/renderer/index.html'));
  await waitFor(`!!document.querySelector('.character-card[aria-label^="安可，"]') || !!document.querySelector('.mod-view-container')`, 'renderer reopened');
  if (await evaluate(`!!document.querySelector('.character-card[aria-label^="安可，"]')`)) await evaluate(`document.querySelector('.character-card[aria-label^="安可，"]').click()`);
  await waitFor(`!!document.querySelector('[data-mod-name="${name}"]')`, 'restored library');
  await evaluate(`document.querySelector('[data-mod-name="${name}"]').click()`);
  await waitFor(`${image}?.naturalHeight === 800 && document.querySelector('.mod-preview-counter')?.textContent === '3 / 3'`, 'choice survives reopening');
  for (const enable of [true, false]) assert.equal((await handlers.get('toggle-mod')({}, { characterName: '安可', modName: name, enable })).success, true);
  assert.equal((await handlers.get('get-mod-details')({}, { characterName: '安可', modName: name })).previewImageId, '画廊/第三张 #.png');
  const renamed = '多图改名';
  assert.equal((await handlers.get('rename-mod')({}, { characterName: '安可', oldName: name, newName: renamed })).success, true);
  const renamedDir = path.join(mods, '安可', 'DISABLED_' + renamed);
  assert.equal((await handlers.get('get-mod-details')({}, { characterName: '安可', modName: renamed })).previewImageId, '画廊/第三张 #.png');
  for (const [file, bytes] of originals) assert.deepEqual(fs.readFileSync(path.join(renamedDir, file)), bytes, 'Original image is untouched: ' + file);
  await waitFor(`!!document.querySelector('[data-mod-name="单图预览"]')`, 'single-image entry');
  await evaluate(`document.querySelector('[data-mod-name="单图预览"]').click()`);
  await waitFor(`${image}?.naturalWidth === 320 && !document.querySelector('.mod-detail-preview .mod-preview-arrow')`, 'single-image preview hides controls');
  // Exercise the EFF route without placing preference metadata in an EFF Mod.
  const runtimeRequire = createRequire(path.join(process.resourcesPath, 'app/package.json'));
  const effRoutes = runtimeRequire('./out/main/mods/eff-routes.cjs');
  const effService = runtimeRequire('./out/main/games/endfield/service.cjs');
  const effDescriptor = Object.getOwnPropertyDescriptor(effService, 'effService');
  const effDir = path.join(path.dirname(mods), 'eff-preview-fixture');
  fs.mkdirSync(effDir); fs.writeFileSync(path.join(effDir, 'preview.png'), originals.get('preview.png')); fs.writeFileSync(path.join(effDir, 'second.png'), originals.get('第二张.png'));
  const effMod = { path: effDir, preview: path.join(effDir, 'preview.png') };
  Object.defineProperty(effService, 'effService', { configurable: true, value: { resolveCharacterMod: () => effMod } });
  try {
    const selected = await handlers.get('select-mod-preview')({}, { characterName: '佩丽卡', modName: 'EFF previews', imageId: 'second.png', gameId: 'endfield' });
    assert.equal(selected.success, true, JSON.stringify(selected));
    assert.equal((await handlers.get('get-mod-details')({}, { characterName: '佩丽卡', modName: 'EFF previews', gameId: 'endfield' })).previewImageId, 'second.png');
    assert.equal(fs.existsSync(path.join(effDir, '.qaqr-preview.json')), false);
    assert.equal(JSON.parse(fs.readFileSync(effRoutes.previewOptions(effMod).stateFile)).image, 'second.png');
  } finally { Object.defineProperty(effService, 'effService', effDescriptor); }
  await captureUI('mod-preview-single.png');
  const call = (channel, payload) => handlers.get(channel)({}, payload);
  await call('game:switch', 'arknights');
  const ark = (await call('game:list')).games.find(game => game.id === 'arknights');
  const arkDir = path.join(ark.modFolderPath, '艾露猫', 'DISABLED_预览测试');
  fs.mkdirSync(path.join(arkDir, 'resources'), { recursive: true });
  fs.writeFileSync(path.join(arkDir, 'preview.png'), originals.get('preview.png'));
  fs.writeFileSync(path.join(arkDir, 'resources/illust_char_4215_buddy_mh_2.png'), originals.get('第二张.png'));
  assert.equal((await call('arknights:sync')).modCount, 0);
  const marker = path.join(path.dirname(ark.modFolderPath), 'Resources/.qaqr-m4a.json');
  const deployedBefore = fs.readFileSync(marker);
  const arkSelected = await call('select-mod-preview', { gameId: 'arknights', characterName: '艾露猫', modName: '预览测试', imageId: 'resources/illust_char_4215_buddy_mh_2.png' });
  assert.equal(arkSelected.success, true, JSON.stringify(arkSelected));
  assert.deepEqual(fs.readFileSync(marker), deployedBefore, 'Selecting a preview never redeploys Arknights resources');
  const listed = (await call('get-mods', '艾露猫')).mods.find(mod => mod.name === '预览测试');
  assert.equal(listed.enabled, false);
  assert.equal(listed.previewUrl, arkSelected.previewUrl);
  assert.equal((await call('get-mod-details', { characterName: '艾露猫', modName: '预览测试' })).previewImageId, 'resources/illust_char_4215_buddy_mh_2.png');
  passed('Preview hover arrows, wraparound, rapid clicks, list/gallery icons, lightbox, reopening, rename/toggle persistence, untouched originals and EFF external preferences');
  passed('Arknights remembers nested resource previews and updates thumbnails without enabling Mods or rebuilding deployed resources');
};
